/**
 * 事業主管理画面のページ幅を統一するコンテナ。
 *
 * ## なぜ必要か（ユーザーFB 2026-08-28）
 *
 * 幅の指定が **layout とページの二重管理** になっていて、1920px で見たときに
 * 画面ごとに実効幅が 512 / 672 / 768 / 896 / 1024 / 全幅 の **6 段階**に
 * バラけていた。原因は「親 layout が `max-w-5xl` で止めているのに、
 * ページ側がさらに `mx-auto max-w-2xl` などを重ねる」構造で、
 * どこを直せば幅が変わるのかがページごとに違っていた。
 *
 * → **幅の実値は `provider/[slug]/layout.tsx` が単独で持つ。**
 *   ページは幅について何も言わない。
 *
 * ## 2 段階（#1314・2026-08-29 ユーザー判断）
 *
 * | 幅 | PC 実効幅 | 宣言の仕方 | 対象 |
 * |---|---|---|---|
 * | 既定 | **1280px** | 何もしない | **スケジュール以外の全ページ** |
 * | 全幅 | 制限なし | `data-page-full` 属性 | **スケジュールのみ** |
 *
 * ### なぜ 3 段（896 / 1280 / 全幅）をやめたか
 *
 * #1280 では「中身のレイアウトが 1 カラムか多カラムか」を軸に 896 / 1280 /
 * 全幅 の 3 段にした。しかし運用してみると分類が実態と合わないページが複数
 * あった。たとえばサービスメニューは PC で
 * `grid-cols-[2rem_1fr_6rem_5rem_5rem_5rem]` の 6 カラムの表なのに 896px 側に
 * 入っていた。**「1 カラムか多カラムか」はページ単位では決まらない**（同じ
 * ページに縦積みの一覧と 4 列のサマリが同居する）ため、分類のたびに判断が要り、
 * その判断がページごとに食い違った。
 *
 * 分類を個別に直すより既定を広い方に倒したほうが**判断の余地が消える**、
 * というのがユーザーの裁定。**例外は設けない。** フォーム・詳細画面も
 * 1280px のコンテナになる。
 *
 * ### 「ページ幅 1280」と「入力欄が 1280 幅で伸びる」は別のレバー
 *
 * ページ幅が広いことは入力欄が広いことを意味しない。フォームの読みやすい幅は
 * **フィールド側**（`src/components/field-width.ts` の `FIELD_MAX_W`）で決める。
 * ページ幅の例外を作ってフォームの間延びを回避しないこと（それは上の裁定に反する）。
 *
 * ## 仕組み
 *
 * このコンポーネントは実際の `max-width` を持たない。sm 未満のモバイルで
 * `max-w-lg`(512px) に収めて中央寄せするだけの薄いラッパで、PC の幅は
 * layout 側の 1 行が決める。ページ側で `max-width` を持つと、layout が描く
 * ヘッダー（`ProviderNav`）と本文の左右がずれる（ヘッダーは children の外にある）。
 *
 * **ページ側に `max-w-*` を書き戻さないこと** — それが今回直した構造そのもの。
 * `src/app/provider/[slug]/__tests__/page-width-tokens.test.ts` が
 * ソース走査で機械的に禁止している。
 *
 * ## `width` prop を廃止した理由（#1314）
 *
 * 3 段のときは `width="grid"` / `width="full"` を受け取っていたが、
 * 2 段になると渡す値が既定しか残らない（全幅を宣言する唯一のページ
 * = スケジュールは、`<main>` 自身が幅ラッパの直下なので PageContainer を
 * 挟まず `data-page-full` 属性だけを付けている）。
 *
 * **「今は誰も渡さないが将来また段を増やすかもしれない」で残さない。**
 * 値を取る prop が残っていると、次に幅で迷った人がそこに新しい段を足せて
 * しまい、#1314 で消したはずの「ページごとに幅を判断する」が戻る。
 * 段を増やすときは layout の 1 行と `data-page-*` を足せばよく、
 * その差分は必ずレビューに乗る。
 */

export function PageContainer({
  className,
  children,
}: {
  className?: string;
  children: React.ReactNode;
}) {
  // sm 未満で 512px に収めて中央寄せ。大きめの端末（横向き・折りたたみ）で
  // 1 行が伸びすぎるのを防ぐ。従来 `mx-auto max-w-lg sm:max-w-none` を
  // 各ページが書いていたのと同じ挙動。
  const mobile = "mx-auto w-full max-w-lg sm:max-w-none";

  return (
    <div className={className ? `${mobile} ${className}` : mobile}>
      {children}
    </div>
  );
}
