/**
 * モーダル / シートの **操作行（送信・キャンセル）をスクロール領域の下端に貼り付ける**（#1691）。
 *
 * ## 何が壊れていたか（運用者・実機 Android / LINE アプリ内ブラウザ・2026-09-03）
 *
 * 「スタッフを追加」のモーダルで氏名欄をタップすると、
 * **ソフトキーボードが出た瞬間にモーダルが縦に縮み、
 * 「作成して招待URLを発行」が下端で切れて押せなくなる。**
 *
 * モーダルの高さは `max-h-[85vh]` のように **ビューポート単位**で決まっている。
 * Android の WebView（LINE アプリ内ブラウザを含む）はソフトキーボードで
 * **レイアウトビューポートごと縮む**ので `85vh` も一緒に縮み、
 * スクロール領域の末尾にある操作行がカードの下端の外へ出る。
 *
 * 実測（dev HEAD `fe6c6f76` / `/provider/team-alpha/members` / 390x844 → 390x380）:
 *
 * | 状態 | カード | 「作成して招待URLを発行」 | 中心の hit-test |
 * |---|---|---|---|
 * | キーボード無し 390x844 | top=150 h=544 bottom=694 | 467..513 | 届く |
 * | **キーボード有り 390x380** | top=29 h=**323** bottom=352 | **346..392** | **届かない**（オーバーレイに当たる） |
 *
 * カードの下端が 352 なのにボタンは 346..392。**6px しか見えていない。**
 *
 * ## なぜ「開いた時点の高さを px で固定する」だけでは直さないのか（#1691 案 1 の実測）
 *
 * 同じ条件で、カードの `max-height` を開いた時点の 85vh（717px）に固定して測った:
 *
 * | 案 | カード | 送信ボタン | **閉じる (×)** |
 * |---|---|---|---|
 * | 案 1（高さ固定 717px） | top=**-82** h=544 bottom=462 | 235..281 届く | **-62..-34 届かない** |
 * | 案 2（この実装） | top=29 h=323 bottom=352 | 286..332 届く | 49..77 届く |
 *
 * 高さを固定すると、カードは縮んだビューポートより背が高くなり
 * **中央寄せの結果 上下が画面外へはみ出す**。送信ボタンは（たまたま中ほどに
 * あるので）押せるようになるが、**ヘッダーと閉じるボタンが画面の外へ出て
 * 押せなくなる**。カードの外側はページなのでスクロールもできない（#951 と同型）。
 * 送信ボタンが末尾ではないカード（発行後の「完了」など）では送信側も同じ目に遭う。
 *
 * つまり **案 1 は問題を別の場所へ移すだけ**なので採らない。採るのは案 2 だけ。
 *
 * ## なぜ `sticky` なのか
 *
 *   - **スクロール領域の外へ出さなくてよい。** 操作行は子フォーム
 *     (`new-member-form` / `new-customer-form`) の中にあり、カードの直下ではない。
 *     `flex flex-col` + 別スクロール領域に組み替えると、
 *     フォーム側から操作行を持ち上げる大改造になる
 *   - **キーボードが無いとき、操作行の位置は 1px も変わらない。**
 *     `position: sticky` は「はみ出すとき」しか効かない。
 *     内容がカードに収まっていれば通常フローのままで、
 *     `bg-card` はカード自身の背景と同じ色なので見えない。
 *
 *     ★ **「1px も変わらない」で止めないこと（#1690）。** `bg-card` を敷くぶん、
 *       `rounded-xl` の角丸の縁に **±2/255 のアンチエイリアス差**が出る。
 *       PR #1706 の before-after 実測（Chromium）:
 *
 *       | 面 | 差分ピクセル数 | 中身 |
 *       |---|---|---|
 *       | クイック作成 | **79px** | 角丸 12 行の ±2/255。位置は完全一致 |
 *       | 休みフォーム | **132px** | 同上 |
 *
 *       視認できないので回帰ではない。**が、断定を写経すると
 *       次に測る人が 79px を見て「回帰だ」と誤認するか、
 *       逆に「変わらないはずだから」と実測を省く。**
 *       次に測る人がこの数字と突き合わせられるように、測った値ごと書くこと。
 *   - 貼り付く位置はスクロールポートの下端 = **カードの内側の余白の縁**
 *     （実測: カード bottom=352 に対しボタン bottom=332 = `p-5` ぶん内側）。
 *     余白を打ち消す負マージンの小細工は要らない
 *
 * ## 使い方
 *
 * ```tsx
 * <SheetActions className="mt-5 flex gap-2">
 *   <button …>キャンセル</button>
 *   <button …>作成する</button>
 * </SheetActions>
 * ```
 *
 * **CSS を各所に写経しないこと。** 方針はこのファイルだけに置く（#1691 の受け入れ基準）。
 * `data-sheet-actions` は e2e / 単体テストがこの方針の適用漏れを検出するための目印。
 */

export const SHEET_ACTIONS_CLASS = "sticky bottom-0 z-10";

/**
 * 貼り付いたときに裏の内容を隠すための不透明な背景。
 * **操作行が乗っている面と同じ色を選ぶこと**（違う色を選ぶと、
 * 貼り付いていない通常時に色の違う帯が見えて「見た目が変わらない」を壊す）。
 *
 *   - `card`       … カード直下の操作行（モーダル / シート本体は `bg-card`）
 *   - `background` … `bg-background` の入れ子パネルの中にある操作行
 *                    （別日にコピーのフォームなど）
 *   - `self`       … **要素自身が既に不透明な背景を塗っている**場合（`bg-accent` など）。
 *                    ここで別の背景クラスを足すと、同じ `background-color` の
 *                    ユーティリティ同士が競合して**どちらが勝つか CSS の出力順次第**になる。
 */
const SURFACE_CLASS = {
  card: "bg-card",
  background: "bg-background",
  self: "",
} as const;

interface SheetActionsProps {
  /** 元の行が持っていたレイアウト用クラス（`mt-5 flex gap-2` など）をそのまま渡す。 */
  className?: string;
  /** 操作行が乗っている面の色。既定はカード直下（`bg-card`）。 */
  surface?: keyof typeof SURFACE_CLASS;
  children: React.ReactNode;
}

export function SheetActions({
  className = "",
  surface = "card",
  children,
}: SheetActionsProps) {
  return (
    <div
      data-sheet-actions=""
      className={`${sheetActionsClass(surface)} ${className}`}
    >
      {children}
    </div>
  );
}

/**
 * **要素を 1 つも増やさずに**同じ方針を当てるためのクラス（操作行がボタン 1 個の場所用）。
 *
 * ## なぜ「ボタンをラップしない」経路が要るのか（実測 2026-09-03）
 *
 * `<button>` は既定で `display: inline-block` なので**マージンが相殺しない**。
 * これを `<div>` で包むと、包んだ div のマージンが**隣接兄弟と相殺する**ため、
 * クイック作成シートの高さが **8px 縮んだ**（before/after のピクセル比較で
 * 差分 25,818px / 7.8%。キーボードが無い状態の見た目が変わっていた）。
 *
 * 操作行が既に `<div className="flex gap-2">` の場所は、その div を
 * {@link SheetActions} に**置き換える**ので要素は増えない。
 * ボタン 1 個の場所だけ、この関数でクラスを直接足す。
 */
export function sheetActionsClass(
  surface: keyof typeof SURFACE_CLASS = "card"
): string {
  return `${SHEET_ACTIONS_CLASS} ${SURFACE_CLASS[surface]}`;
}
